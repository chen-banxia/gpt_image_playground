export type TranslationKey = keyof typeof translations.en

let activeLanguage: Language = 'en'

export function getLanguage(settingsLanguage?: Language): Language {
  return settingsLanguage === 'zh' ? 'zh' : 'en'
}

export function setActiveLanguage(language: Language) {
  activeLanguage = getLanguage(language)
}

export function getActiveLanguage() {
  return activeLanguage
}

export function tCurrent(key: TranslationKey, replacements?: Record<string, string | number>) {
  return translate(activeLanguage, key, replacements)
}

export function translate(language: Language, key: TranslationKey, replacements?: Record<string, string | number>): string {
  const text = String(translations[getLanguage(language)][key] ?? translations.en[key])
  if (!replacements) return text
  return Object.entries(replacements).reduce(
    (value, [name, replacement]) => value.split(`{${name}}`).join(String(replacement)),
    text,
  )
}
