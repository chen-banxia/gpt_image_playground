export const videoZh = Object.fromEntries(Object.keys(videoEn).map(key => [key, key])) as { [K in keyof typeof videoEn]: K }

const messageTemplates = Object.entries(videoEn).flatMap(([zh, en]) => {
  if (!zh.includes('{')) return []
  return ([zh, en] as const).map(source => {
    const slots: string[] = []
    const escaped = source.split(/(\{\d+\})/).map(part => {
      if (/^\{\d+\}$/.test(part)) { slots.push(part.slice(1, -1)); return '([\\s\\S]*?)' }
      return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    }).join('')
    return { zh, en, slots, pattern: new RegExp(`^${escaped}$`) }
  })
})
const reverseMessages = new Map(Object.entries(videoEn).map(([zh, en]) => [en as string, zh]))

/** 仅用于应用生成的历史提示；插值值原样保留，未知上游错误也保持原文。 */
export function localizeVideoMessage(language: 'zh' | 'en', text: string): string {
  if (Object.prototype.hasOwnProperty.call(videoEn, text)) return language === 'en' ? videoEn[text as keyof typeof videoEn] : text
  const original = reverseMessages.get(text)
  if (original !== undefined) return language === 'zh' ? original : text
  for (const { zh, en, slots, pattern } of messageTemplates) {
    const match = pattern.exec(text)
    if (!match) continue
    const replacements = Object.fromEntries(slots.map((slot, index) => [slot, match[index + 1]]))
    return (language === 'en' ? en : zh).replace(/\{(\d+)\}/g, (token, slot) => replacements[slot] ?? token)
  }
  return text
}
